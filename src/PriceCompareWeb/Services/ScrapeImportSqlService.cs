            await writer.WriteLineAsync("  lastseenat = GREATEST(p.lastseenat, d.lastseenat)");
            await writer.WriteLineAsync("FROM (");
            await writer.WriteLineAsync("  SELECT DISTINCT ON (v.shoptype, v.sourceid)");
