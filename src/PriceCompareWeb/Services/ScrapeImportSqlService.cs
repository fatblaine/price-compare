    public class ScrapeImportSqlService : IScrapeImportSqlService
    {
        private readonly ScrapeExportOptions _options;
        private readonly IHostEnvironment _env;
        private readonly ILogger<ScrapeImportSqlService> _logger;

        public ScrapeImportSqlService(
            IOptions<ScrapeExportOptions> options,
            IHostEnvironment env,
            ILogger<ScrapeImportSqlService> logger)
        {
            _options = options.Value;
            _env = env;
            _logger = logger;
        }

        public async Task<ScrapeImportSqlResult> GenerateAsync(ScrapeImportSqlRequest request, CancellationToken ct = default)
        {
            if (string.IsNullOrWhiteSpace(request.ExportDir))
            {
                throw new InvalidOperationException("ExportDir is required.");
            }

            var root = ResolveRoot();
            var exportDir = ResolveUnderRoot(root, request.ExportDir);

            if (!Directory.Exists(exportDir))
            {
                throw new InvalidOperationException($"Export directory not found: {exportDir}");
            }

            var outputPath = ResolveOutputPath(exportDir, request.OutputPath);
            Directory.CreateDirectory(Path.GetDirectoryName(outputPath)!);

            var batchSize = request.BatchSize ?? _options.BatchSize;
            if (batchSize <= 0) batchSize = 500;
            if (batchSize > 5000) batchSize = 5000;

            var priceHistoryPath = Path.Combine(exportDir, "pricehistory.csv");
            var productPath = Path.Combine(exportDir, "product.csv");

            if (!File.Exists(priceHistoryPath) && !File.Exists(productPath))
            {
                throw new InvalidOperationException("No CSV files found in export directory.");
            }

            await using var stream = new FileStream(outputPath, FileMode.Create, FileAccess.Write, FileShare.Read);
            await using var writer = new StreamWriter(stream, new UTF8Encoding(false));

            await writer.WriteLineAsync($"-- Generated by ScrapeImportSqlService at {DateTime.UtcNow:O}");
            await writer.WriteLineAsync("BEGIN;");

            var priceHistoryRows = 0;
            if (File.Exists(priceHistoryPath))
            {
                priceHistoryRows = await WritePriceHistorySqlAsync(writer, priceHistoryPath, batchSize, ct);
            }

            var productRows = 0;
            if (File.Exists(productPath))
            {
                productRows = await WriteProductSqlAsync(writer, productPath, batchSize, ct);
            }

            if (priceHistoryRows > 0)
            {
                await writer.WriteLineAsync("-- reset pricehistory id sequence");
                await writer.WriteLineAsync("SELECT setval(");
                await writer.WriteLineAsync("  pg_get_serial_sequence('pricehistory','id'),");
                await writer.WriteLineAsync("  COALESCE((SELECT MAX(id) FROM pricehistory), 0) + 1,");
                await writer.WriteLineAsync("  false");
                await writer.WriteLineAsync(");");
                await writer.WriteLineAsync();
            }

            await writer.WriteLineAsync("COMMIT;");

            _logger.LogInformation("Generated SQL file at {Path}", outputPath);

            string? preview = null;
            if (request.IncludeSql)
            {
                preview = await ReadPreviewAsync(outputPath, 4000, ct);
            }

            return new ScrapeImportSqlResult(
                exportDir,
                outputPath,
                priceHistoryRows,
                productRows,
                preview);
        }

        private string ResolveRoot()
        {
            var root = string.IsNullOrWhiteSpace(_options.ExportDir) ? "exports" : _options.ExportDir;
            return Path.IsPathRooted(root)
                ? root
                : Path.Combine(_env.ContentRootPath, root);
        }

        private static string ResolveUnderRoot(string root, string requested)
        {
            var basePath = Path.GetFullPath(root);
            var target = Path.IsPathRooted(requested)
                ? Path.GetFullPath(requested)
                : Path.GetFullPath(Path.Combine(basePath, requested));

            if (!target.StartsWith(basePath, StringComparison.OrdinalIgnoreCase))
            {
                throw new InvalidOperationException("ExportDir must be under the configured export root.");
            }

            return target;
        }

        private static string ResolveOutputPath(string exportDir, string? outputPath)
        {
            if (string.IsNullOrWhiteSpace(outputPath))
            {
                return Path.Combine(exportDir, "import.sql");
            }

            var target = Path.IsPathRooted(outputPath)
                ? Path.GetFullPath(outputPath)
                : Path.GetFullPath(Path.Combine(exportDir, outputPath));

            var basePath = Path.GetFullPath(exportDir);
            if (!target.StartsWith(basePath, StringComparison.OrdinalIgnoreCase))
            {
                throw new InvalidOperationException("OutputPath must be under the export directory.");
            }

            return target;
        }

        private static async Task<int> WritePriceHistorySqlAsync(
            StreamWriter writer,
            string csvPath,
            int batchSize,
            CancellationToken ct)
        {
            await writer.WriteLineAsync("-- pricehistory");
            var total = 0;
            var batch = new List<PriceHistoryRow>(batchSize);

            await foreach (var row in CsvRecordReader.ReadAsync(csvPath, ct))
            {
                if (row.IsHeader)
                {
                    continue;
                }

                if (row.Values.Count == 0)
                {
                    continue;
                }

                if (row.Values.All(string.IsNullOrWhiteSpace))
                {
                    continue;
                }

                var parsed = PriceHistoryRow.FromCsv(row.Values, row.HeaderMap);
                batch.Add(parsed);
                total++;

                if (batch.Count >= batchSize)
                {
                    await WritePriceHistoryBatchAsync(writer, batch, ct);
                    batch.Clear();
                }
            }

            if (batch.Count > 0)
            {
                await WritePriceHistoryBatchAsync(writer, batch, ct);
            }

            return total;
        }

        private static async Task<int> WriteProductSqlAsync(
            StreamWriter writer,
            string csvPath,
            int batchSize,
            CancellationToken ct)
        {
            await writer.WriteLineAsync("-- product");
            var total = 0;
            var withSource = new List<ProductRow>(batchSize);
            var withoutSource = new List<ProductRow>(batchSize);

            await foreach (var row in CsvRecordReader.ReadAsync(csvPath, ct))
            {
                if (row.IsHeader)
                {
                    continue;
                }

                if (row.Values.Count == 0)
                {
                    continue;
                }

                if (row.Values.All(string.IsNullOrWhiteSpace))
                {
                    continue;
                }

                var parsed = ProductRow.FromCsv(row.Values, row.HeaderMap);
                total++;

                if (!HasUsableSourceId(parsed))
                {
                    parsed = parsed with { SourceId = null };
                    withoutSource.Add(parsed);
                    if (withoutSource.Count >= batchSize)
                    {
                        await WriteProductBatchWithoutSourceAsync(writer, withoutSource, ct);
                        withoutSource.Clear();
                    }
                }
                else
                {
                    withSource.Add(parsed);
                    if (withSource.Count >= batchSize)
                    {
                        await WriteProductBatchWithSourceAsync(writer, withSource, ct);
                        withSource.Clear();
                    }
                }
            }

            if (withSource.Count > 0)
            {
                await WriteProductBatchWithSourceAsync(writer, withSource, ct);
            }

            if (withoutSource.Count > 0)
            {
                await WriteProductBatchWithoutSourceAsync(writer, withoutSource, ct);
            }

            return total;
        }

        private static bool HasUsableSourceId(ProductRow row)
        {
            if (string.IsNullOrWhiteSpace(row.SourceId))
            {
                return false;
            }

            // Historical export bug could serialize missing WWS IDs as "0".
            return !string.Equals(row.SourceId.Trim(), "0", StringComparison.Ordinal);
        }

        private static async Task WritePriceHistoryBatchAsync(StreamWriter writer, IReadOnlyList<PriceHistoryRow> batch, CancellationToken ct)
        {
            await writer.WriteLineAsync("WITH v(name, currentprice, imageurl, scrapedat, offertype, shoptype, promotext) AS (");
            await writer.WriteLineAsync("  VALUES");

            for (var i = 0; i < batch.Count; i++)
            {
                var row = batch[i];
                var line = $"  ({Sql.Text(row.Name, false)}, {Sql.Decimal(row.CurrentPrice)}, {Sql.Text(row.ImageUrl, false)}, {Sql.Timestamp(row.ScrapedAt)}, {Sql.Int(row.OfferType)}, {Sql.Int(row.ShopType)}, {Sql.Text(row.PromoText, true)})";
                line += i == batch.Count - 1 ? string.Empty : ",";
                await writer.WriteLineAsync(line);
            }

            await writer.WriteLineAsync(")");
            await writer.WriteLineAsync("UPDATE pricehistory ph");
            await writer.WriteLineAsync("SET currentprice = v.currentprice,");
            await writer.WriteLineAsync("    imageurl = v.imageurl,");
            await writer.WriteLineAsync("    scrapedat = v.scrapedat,");
            await writer.WriteLineAsync("    promotext = v.promotext");
            await writer.WriteLineAsync("FROM v");
            await writer.WriteLineAsync("WHERE ph.name = v.name");
            await writer.WriteLineAsync("  AND ph.shoptype IS NOT DISTINCT FROM v.shoptype");
            await writer.WriteLineAsync("  AND ph.offertype IS NOT DISTINCT FROM v.offertype");
            await writer.WriteLineAsync("  AND ph.scrapedat::date = v.scrapedat::date;");
            await writer.WriteLineAsync();
            await writer.WriteLineAsync("WITH v(name, currentprice, imageurl, scrapedat, offertype, shoptype, promotext) AS (");
            await writer.WriteLineAsync("  VALUES");

            for (var i = 0; i < batch.Count; i++)
            {
                var row = batch[i];
                var line = $"  ({Sql.Text(row.Name, false)}, {Sql.Decimal(row.CurrentPrice)}, {Sql.Text(row.ImageUrl, false)}, {Sql.Timestamp(row.ScrapedAt)}, {Sql.Int(row.OfferType)}, {Sql.Int(row.ShopType)}, {Sql.Text(row.PromoText, true)})";
                line += i == batch.Count - 1 ? string.Empty : ",";
                await writer.WriteLineAsync(line);
            }

            await writer.WriteLineAsync(")");
            await writer.WriteLineAsync("INSERT INTO pricehistory (name, currentprice, imageurl, scrapedat, offertype, shoptype, promotext)");
            await writer.WriteLineAsync("SELECT v.name, v.currentprice, v.imageurl, v.scrapedat, v.offertype, v.shoptype, v.promotext");
            await writer.WriteLineAsync("FROM v");
            await writer.WriteLineAsync("WHERE NOT EXISTS (");
            await writer.WriteLineAsync("  SELECT 1 FROM pricehistory ph");
            await writer.WriteLineAsync("  WHERE ph.name = v.name");
            await writer.WriteLineAsync("    AND ph.shoptype IS NOT DISTINCT FROM v.shoptype");
            await writer.WriteLineAsync("    AND ph.offertype IS NOT DISTINCT FROM v.offertype");
            await writer.WriteLineAsync("    AND ph.scrapedat::date = v.scrapedat::date");
            await writer.WriteLineAsync(");");
            await writer.WriteLineAsync();
        }

        private static async Task WriteProductBatchWithSourceAsync(StreamWriter writer, IReadOnlyList<ProductRow> batch, CancellationToken ct)
        {
            await writer.WriteLineAsync("UPDATE product p SET");
            await writer.WriteLineAsync("  name = d.name,");
            await writer.WriteLineAsync("  brand = COALESCE(d.brand, p.brand),");
            await writer.WriteLineAsync("  sizevalue = COALESCE(d.sizevalue, p.sizevalue),");
            await writer.WriteLineAsync("  sizeunit = COALESCE(d.sizeunit, p.sizeunit),");
            await writer.WriteLineAsync("  packageqty = COALESCE(d.packageqty, p.packageqty),");
            await writer.WriteLineAsync("  categoryid = COALESCE(d.categoryid, p.categoryid),");
