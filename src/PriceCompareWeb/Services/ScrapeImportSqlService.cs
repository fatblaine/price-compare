        private static async Task<string> ReadPreviewAsync(string path, int maxChars, CancellationToken ct)
        {
            await using var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite);
            using var reader = new StreamReader(stream, Encoding.UTF8, detectEncodingFromByteOrderMarks: true, leaveOpen: false);
            var buffer = new char[maxChars];
            var read = await reader.ReadAsync(buffer.AsMemory(0, maxChars), ct);
            return new string(buffer, 0, read);
        }

        private record PriceHistoryRow(
            string Name,
            decimal CurrentPrice,
            string ImageUrl,
            DateTime ScrapedAt,
            int? OfferType,
            int? ShopType,
            string? PromoText)
        {
            public static PriceHistoryRow FromCsv(IReadOnlyList<string> values, IReadOnlyDictionary<string, int> map)
            {
                string? promoText = null;
                if (map.TryGetValue("promotext", out var idx) && idx >= 0 && idx < values.Count)
                {
                    promoText = values[idx];
                }

                return new PriceHistoryRow(
                    Csv.Get(values, map, "name", required: true),
                    Csv.Decimal(values, map, "currentprice"),
                    Csv.Get(values, map, "imageurl", required: true),
                    Csv.Timestamp(values, map, "scrapedat"),
                    Csv.Int(values, map, "offertype"),
                    Csv.Int(values, map, "shoptype"),
                    string.IsNullOrWhiteSpace(promoText) ? null : promoText);
            }
        }

        private record ProductRow(
            int? ShopType,
            string? SourceId,
            string Name,
            string? Brand,
            decimal? SizeValue,
            string? SizeUnit,
            int? PackageQty,
            int? CategoryId,
            string? ImageUrl,
            DateTime LastSeenAt,
            string NormalizedName,
            string? NormalizedBrand,
            decimal? SizeStandardValue,
            string? SizeStandardUnit,
            bool SizeUnknown,
            bool BrandUnknown,
            bool CategoryUnknown)
        {
            public static ProductRow FromCsv(IReadOnlyList<string> values, IReadOnlyDictionary<string, int> map)
            {
                var normalizedBrand = Csv.Get(values, map, "normalizedbrand", required: false);
                if (string.IsNullOrWhiteSpace(normalizedBrand))
                {
                    normalizedBrand = null;
                }

                var sizeStandardUnit = Csv.Get(values, map, "sizestandardunit", required: false);
                if (string.IsNullOrWhiteSpace(sizeStandardUnit))
                {
                    sizeStandardUnit = null;
                }

                return new ProductRow(
                    Csv.Int(values, map, "shoptype"),
                    Csv.Get(values, map, "sourceid", required: false),
                    Csv.Get(values, map, "name", required: true),
                    Csv.Get(values, map, "brand", required: false),
                    Csv.DecimalNullable(values, map, "sizevalue"),
                    Csv.Get(values, map, "sizeunit", required: false),
                    Csv.Int(values, map, "packageqty"),
                    Csv.Int(values, map, "categoryid"),
                    Csv.Get(values, map, "imageurl", required: false),
                    Csv.Timestamp(values, map, "lastseenat"),
                    Csv.Get(values, map, "normalizedname", required: true),
                    normalizedBrand,
                    Csv.DecimalNullable(values, map, "sizestandardvalue"),
                    sizeStandardUnit,
                    Csv.Bool(values, map, "sizeunknown"),
                    Csv.Bool(values, map, "brandunknown"),
                    Csv.Bool(values, map, "categoryunknown"));
            }
        }

        private static class Sql
        {
            public static string Text(string? value, bool emptyAsNull)
            {
                if (string.IsNullOrEmpty(value))
                {
                    return emptyAsNull ? "NULL" : "''";
                }

                return $"'{value.Replace("'", "''")}'";
            }

            public static string Int(int? value)
                => value.HasValue ? value.Value.ToString(CultureInfo.InvariantCulture) : "NULL";

            public static string Decimal(decimal? value)
                => value.HasValue ? value.Value.ToString(CultureInfo.InvariantCulture) : "NULL";

            public static string Bool(bool? value)
            {
                if (!value.HasValue)
                {
                    return "NULL";
                }

                return value.Value ? "true" : "false";
            }

            public static string Timestamp(DateTime value)
                => $"'{value.ToUniversalTime():O}'::timestamptz";
        }

        private static class Csv
        {
            public static string Get(IReadOnlyList<string> values, IReadOnlyDictionary<string, int> map, string column, bool required)
            {
                if (!map.TryGetValue(column, out var idx))
                {
                    throw new InvalidOperationException($"Missing column '{column}'.");
                }

                if (idx < 0 || idx >= values.Count)
                {
                    return string.Empty;
                }

                var value = values[idx];
                if (required && string.IsNullOrWhiteSpace(value))
                {
                    throw new InvalidOperationException($"Column '{column}' is required.");
                }

                return value;
            }

            public static int? Int(IReadOnlyList<string> values, IReadOnlyDictionary<string, int> map, string column)
            {
                var raw = Get(values, map, column, required: false);
                if (string.IsNullOrWhiteSpace(raw))
                {
                    return null;
                }

                return int.TryParse(raw, NumberStyles.Integer, CultureInfo.InvariantCulture, out var parsed)
                    ? parsed
                    : null;
            }

            public static decimal Decimal(IReadOnlyList<string> values, IReadOnlyDictionary<string, int> map, string column)
            {
                var raw = Get(values, map, column, required: true);
                if (decimal.TryParse(raw, NumberStyles.Number, CultureInfo.InvariantCulture, out var parsed))
                {
                    return parsed;
                }

                throw new InvalidOperationException($"Invalid decimal in column '{column}'.");
            }

            public static decimal? DecimalNullable(IReadOnlyList<string> values, IReadOnlyDictionary<string, int> map, string column)
            {
                var raw = Get(values, map, column, required: false);
                if (string.IsNullOrWhiteSpace(raw))
                {
                    return null;
                }

                return decimal.TryParse(raw, NumberStyles.Number, CultureInfo.InvariantCulture, out var parsed)
                    ? parsed
                    : null;
            }

            public static DateTime Timestamp(IReadOnlyList<string> values, IReadOnlyDictionary<string, int> map, string column)
            {
                var raw = Get(values, map, column, required: true);
                if (DateTime.TryParse(raw, CultureInfo.InvariantCulture, DateTimeStyles.AssumeUniversal | DateTimeStyles.AdjustToUniversal, out var parsed))
                {
                    return parsed;
                }

                throw new InvalidOperationException($"Invalid datetime in column '{column}'.");
            }

            public static bool Bool(IReadOnlyList<string> values, IReadOnlyDictionary<string, int> map, string column)
            {
                var raw = Get(values, map, column, required: true).Trim();
                if (bool.TryParse(raw, out var parsed))
                {
                    return parsed;
                }

                if (string.Equals(raw, "1", StringComparison.OrdinalIgnoreCase))
                {
                    return true;
                }

                if (string.Equals(raw, "0", StringComparison.OrdinalIgnoreCase))
                {
                    return false;
                }

                throw new InvalidOperationException($"Invalid boolean in column '{column}'.");
            }
        }

        private readonly record struct CsvRow(bool IsHeader, IReadOnlyList<string> Values, IReadOnlyDictionary<string, int> HeaderMap);

        private static class CsvRecordReader
        {
            public static async IAsyncEnumerable<CsvRow> ReadAsync(string path, [System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken ct)
            {
                await using var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite);
                using var reader = new StreamReader(stream, Encoding.UTF8, detectEncodingFromByteOrderMarks: true);

                var headerMap = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
                var isHeader = true;

                foreach (var record in ReadRecords(reader))
                {
                    if (ct.IsCancellationRequested)
                    {
                        yield break;
                    }

                    if (isHeader)
                    {
                        for (var i = 0; i < record.Count; i++)
                        {
                            var key = record[i]?.Trim() ?? string.Empty;
                            if (!string.IsNullOrEmpty(key) && !headerMap.ContainsKey(key))
                            {
                                headerMap[key] = i;
                            }
                        }

                        yield return new CsvRow(true, record, headerMap);
                        isHeader = false;
                        continue;
                    }

                    yield return new CsvRow(false, record, headerMap);
                }
            }

            private static IEnumerable<IReadOnlyList<string>> ReadRecords(TextReader reader)
            {
                var record = new List<string>();
                var field = new StringBuilder();
                var inQuotes = false;

                while (true)
                {
                    var ch = reader.Read();
                    if (ch == -1)
                    {
                        if (inQuotes)
                        {
                            inQuotes = false;
                        }

                        if (field.Length > 0 || record.Count > 0)
                        {
                            record.Add(field.ToString());
                            yield return record;
                        }

                        yield break;
                    }

                    var c = (char)ch;

                    if (inQuotes)
                    {
                        if (c == '"')
                        {
                            var peek = reader.Peek();
                            if (peek == '"')
                            {
                                reader.Read();
                                field.Append('"');
                            }
                            else
                            {
                                inQuotes = false;
                            }
                        }
                        else
                        {
                            field.Append(c);
                        }

                        continue;
                    }

                    if (c == '"')
                    {
                        inQuotes = true;
                        continue;
                    }

                    if (c == ',')
                    {
                        record.Add(field.ToString());
                        field.Clear();
                        continue;
                    }

                    if (c == '\r' || c == '\n')
                    {
                        if (c == '\r' && reader.Peek() == '\n')
                        {
                            reader.Read();
                        }

                        record.Add(field.ToString());
                        field.Clear();
                        yield return record;
                        record = new List<string>();
                        continue;
                    }

                    field.Append(c);
                }
            }
        }
